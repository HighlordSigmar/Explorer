-- Builds Instances.lua from InstanceJournal's database (public domain,
-- https://github.com/Arthur-Helias/InstanceJournal). Run with Lua 5.0:
--   lua50 devkit/gen_instances.lua /path/to/InstanceJournal/ > Instances.lua

local D = arg[1]
function GetLocale() return "enUS" end
setmetatable(getfenv(0), { __index = function(t, k)
  if type(k) == "string" and string.find(k, "^IJ_") then return k end
end })
dofile(D .. "locale/InstanceJournal-enUS.lua")
dofile(D .. "InstanceJournalLib.lua")
dofile(D .. "InstanceJournalDB.lua")
for line in io.lines(D .. "InstanceJournal.toc") do
  local _, _, f = string.find(line, "^(db\\%a+\\[%w_]+%.lua)")
  if f then dofile(D .. string.gsub(f, "\\", "/")) end
end

dofile("devkit/zones.lua")
local ZONES = ZONE_LIST
local function ZoneName(c, z)
  local list = ZONES[tonumber(c)]
  local name = list and list[tonumber(z)]
  if not name then error("unknown zone " .. tostring(c) .. ":" .. tostring(z)) end
  return name
end

-- check: every POI name must equal its zone name in our list
for key, poi in pairs(IJDB.POI) do
  local zn = ZoneName(poi.MapContinentId, poi.MapZoneId)
  if zn ~= poi.Name then error("POI " .. key .. ": " .. poi.Name .. " ~= " .. zn) end
end

local function sorted(t)
  local keys = {}
  for k in pairs(t) do table.insert(keys, k) end
  table.sort(keys)
  return keys
end

local function num(v) return string.format("%.1f", v) end

local out = {}
local function w(s) table.insert(out, s) end

w("-- Explorer: dungeons, raids and world bosses of OctoWoW.")
w("-- Generated by devkit/gen_instances.lua from InstanceJournal's database")
w("-- (public domain, https://github.com/Arthur-Helias/InstanceJournal).")
w("-- Coordinates are 0-100 on the zone map, like the game's coordinates.")
w("")
w("Explorer = Explorer or {}")
w("")
w("-- key = { name, kind, min level, max level, instance map (SetMapZoom), first floor }")
w("Explorer.Instances = {")
local placed = {}   -- zone pins: [c][zone] = { {x, y, kind, ids...} }
local function Pin(c, zone, pin)
  placed[c] = placed[c] or {}
  placed[c][zone] = placed[c][zone] or {}
  table.insert(placed[c][zone], pin)
end
local inPoi = {}    -- [c..":"..poiZone] = { instance keys }
for _, db in ipairs({ "DG", "R" }) do
  for _, key in ipairs(sorted(IJDB[db])) do
    local inst = IJDB[db][key]
    if key ~= "WORLD" then
      local kind = (inst.Type == IJLib.InstanceType.Raid) and "raid" or "dungeon"
      w(string.format("  [%q] = { %q, %q, %d, %d, %d },", key, inst.Name, kind,
        inst.MinLevel, inst.MaxLevel, inst.MapId))
      for i, e in pairs(inst.Entrances or {}) do
        local c = tonumber(e.MapContinentId)
        if c == 1 or c == 2 then
          local zone = ZoneName(c, e.MapZoneId)
          Pin(c, zone, { x = e.MapCoordinateX, y = e.MapCoordinateY, kind = kind, id = key,
            floor = e.MapDestinationZoneId })
          local k = c .. ":" .. zone
          inPoi[k] = inPoi[k] or {}
          if inPoi[k][table.getn(inPoi[k])] ~= key then table.insert(inPoi[k], key) end
        end
      end
    end
  end
end
w("}")
w("")

-- POI sub-maps (Blackrock Mountain, Dire Maul...) get a pin on every outdoor
-- zone that leads into them, listing the instances inside
for _, key in ipairs(sorted(IJDB.POI)) do
  local poi = IJDB.POI[key]
  local c = tonumber(poi.MapContinentId)
  local inside = inPoi[c .. ":" .. poi.Name]
  if inside then
    local kind = "raid"
    for _, id in ipairs(inside) do
      if IJDB.DG[id] then kind = "dungeon" end
    end
    for _, e in pairs(poi.Entrances) do
      local ec = tonumber(e.MapContinentId)
      Pin(ec, ZoneName(ec, e.MapZoneId), { x = e.MapCoordinateX, y = e.MapCoordinateY,
        kind = kind, poi = poi.Name, ids = inside })
    end
  end
end

-- world bosses
for _, boss in ipairs(IJDB.R.WORLD.Bosses) do
  if boss.MapId and boss.MapZoneId then
    local c = tonumber(boss.MapId)
    Pin(c, ZoneName(c, boss.MapZoneId), { x = boss.MapCoordinateX, y = boss.MapCoordinateY,
      kind = "worldboss", name = boss.Name })
  end
end

w("-- [continent][zone] = pins. kind: dungeon, raid, worldboss.")
w("-- id = one instance; poi = a sub-map with these instances (ids) inside")
w("Explorer.InstancePins = {")
for _, c in ipairs({ 1, 2 }) do
  w(string.format("  [%d] = {", c))
  for _, zone in ipairs(sorted(placed[c])) do
    local pins = placed[c][zone]
    table.sort(pins, function(a, b) return a.x < b.x or (a.x == b.x and a.y < b.y) end)
    w(string.format("    [%q] = {", zone))
    for _, p in ipairs(pins) do
      local extra
      if p.id then
        extra = string.format("id = %q", p.id)
        if p.floor then extra = extra .. string.format(", floor = %d", p.floor) end
      elseif p.poi then
        local ids = {}
        for _, id in ipairs(p.ids) do table.insert(ids, string.format("%q", id)) end
        extra = string.format("poi = %q, ids = { %s }", p.poi, table.concat(ids, ", "))
      else
        extra = string.format("name = %q", p.name)
      end
      w(string.format("      { %s, %s, %q, %s },", num(p.x), num(p.y), p.kind, extra))
    end
    w("    },")
  end
  w("  },")
end
w("}")

io.write(table.concat(out, "\n") .. "\n")
